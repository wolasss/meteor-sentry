// Builds lib/vendor/sentry-browser.js, the Sentry SDK the client loads.
//
// Meteor's package bundler has no tree shaking: an app gets every module an import
// reaches. Imported from npm, @sentry/browser 11 put 1.1 MiB into an app's initial
// bundle, 509 KiB of it @sentry/conventions constants the SDK barely uses. esbuild
// keeps only what the exported functions reach.
//
// CI rebuilds this file and fails if the result differs from the committed one.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const OUTPUT = new URL('lib/vendor/sentry-browser.js', root);
const BUNDLED_PACKAGES = new URL('scripts/client-sdk-packages.json', root);

// Left out of Logger.Sentry on the client. Session replay, the feedback widget and
// browser profiling are half the SDK's size, and none of them runs unless an app adds
// it. Removing a name from this list is a feature; adding one is a breaking change.
const EXCLUDED_EXPORTS = [
    'replayIntegration',
    'replayCanvasIntegration',
    'getReplay',
    'feedbackIntegration',
    'feedbackAsyncIntegration',
    'feedbackSyncIntegration',
    'getFeedback',
    'sendFeedback',
    'browserProfilingIntegration',
    'uiProfiler'
];

// The packages behind the excluded exports. A kept export that reached one of them
// would bring the size back, so the build fails instead.
const EXCLUDED_PACKAGES = ['@sentry/replay', '@sentry/replay-canvas', '@sentry/feedback'];

const readJson = url => JSON.parse(readFileSync(url, 'utf8'));
const packageJson = name => readJson(new URL(`node_modules/${name}/package.json`, root));

// The client and server SDKs share @sentry/core; one Sentry version across both
// keeps them reporting the same way.
function checkSdkVersions() {
    const nodeVersion = readFileSync(new URL('package.js', root), 'utf8').match(/'@sentry\/node': '([^']+)'/)?.[1];
    const browserVersion = packageJson('@sentry/browser').version;

    if(nodeVersion !== browserVersion) {
        throw new Error(`@sentry/browser ${browserVersion} (package.json) must match @sentry/node ${nodeVersion} (package.js Npm.depends)`);
    }

    return browserVersion;
}

async function sdkExportNames() {
    const result = await build({
        stdin: { contents: "export * from '@sentry/browser';", resolveDir: root.pathname },
        bundle: true,
        write: false,
        metafile: true,
        format: 'esm',
        platform: 'browser',
        logLevel: 'error'
    });

    return Object.values(result.metafile.outputs)[0].exports;
}

function packageOf(inputPath) {
    const parts = inputPath.split('node_modules/').pop().split('/');

    return parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
}

const version = checkSdkVersions();
const exportNames = await sdkExportNames();
const unknownExclusions = EXCLUDED_EXPORTS.filter(name => !exportNames.includes(name));

// A renamed integration would otherwise slip back in under its new name.
if(unknownExclusions.length) {
    throw new Error(`@sentry/browser ${version} no longer exports: ${unknownExclusions.join(', ')}. Update EXCLUDED_EXPORTS.`);
}

const keptNames = exportNames.filter(name => !EXCLUDED_EXPORTS.includes(name)).sort();
const result = await build({
    stdin: { contents: `export { ${keptNames.join(', ')} } from '@sentry/browser';`, resolveDir: root.pathname },
    bundle: true,
    write: false,
    metafile: true,
    format: 'esm',
    platform: 'browser',
    // Identifiers stay, so stack frames inside the SDK keep their function names.
    minifySyntax: true,
    minifyWhitespace: true,
    legalComments: 'none',
    banner: {
        js: [
            `// Generated by scripts/build-client-sdk.mjs from @sentry/browser ${version}. Do not edit: run \`npm run build:client-sdk\`.`,
            '// Sentry JavaScript SDK, MIT License, Copyright (c) 2019 Functional Software, Inc. dba Sentry.'
        ].join('\n')
    },
    logLevel: 'error'
});

// esbuild parses modules it then drops; only inputs with bytes in the output ship.
const shippedInputs = Object.entries(Object.values(result.metafile.outputs)[0].inputs)
    .filter(([path, input]) => input.bytesInOutput > 0 && path.includes('node_modules/'))
    .map(([path]) => path);
const bundledPackages = [...new Set(shippedInputs.map(packageOf))].sort();
const leaked = bundledPackages.filter(name => EXCLUDED_PACKAGES.includes(name));

if(leaked.length) {
    throw new Error(`A kept export reaches ${leaked.join(', ')}. Exclude the export that does.`);
}

writeFileSync(OUTPUT, result.outputFiles[0].contents);

// The shrinkwrap no longer lists these, so the runtime advisory audit reads them here.
writeFileSync(BUNDLED_PACKAGES, JSON.stringify(Object.fromEntries(bundledPackages.map(name => [name, { version: packageJson(name).version }])), null, 4) + '\n');

console.log(`lib/vendor/sentry-browser.js: @sentry/browser ${version}, ${keptNames.length} exports, ${(result.outputFiles[0].contents.length / 1024).toFixed(0)} KiB`);
